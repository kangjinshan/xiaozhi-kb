#!/usr/bin/env python3
"""Generate the original, deterministic 24 kHz send-success swoosh asset."""
import math
from pathlib import Path
import random


def samples():
    rate = 24000
    count = rate * 160 // 1000
    rng = random.Random(2112)
    phase = 0.0
    low = high = 0.0
    sound = []
    for index in range(count):
        t = index / (count - 1)
        phase += 2 * math.pi * (2400 - 1800 * t) / rate
        noise = rng.uniform(-1, 1)
        low += 0.65 * (noise - low)
        high += 0.07 * (noise - high)
        envelope = math.sin(math.pi * t) ** 1.6
        sound.append(envelope * (0.78 * math.sin(phase) + 0.30 * (low - high)))
    scale = 11000 / max(abs(value) for value in sound)
    # Allow the I2S DMA queue to drain before the amplifier closes.
    return [round(value * scale) for value in sound] + [0] * (rate * 80 // 1000)


def main():
    target = Path(__file__).resolve().parents[1] / "main/apps/recorder/recorder_send_cue_pcm.inc"
    pcm = samples()
    lines = ["// Generated by scripts/generate_recorder_send_cue.py; PCM16 mono, 24000 Hz."]
    lines += [", ".join(map(str, pcm[index:index + 16])) + "," for index in range(0, len(pcm), 16)]
    target.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
